// Pure Dart (no Flutter/Flame imports) so `dart run kiln:types` can use it.

/// Dart source with typed names for a project's scenes: scene asset paths, event names and
/// variable accessors. [scenes] maps asset path (`assets/scenes/x.kiln.json`) to decoded JSON.
String generateTypes(Map<String, Object?> scenes) {
  final assets = scenes.keys.toList()..sort();
  final events = <String>{};
  final vars = <String, String>{};

  void addVar(String name, String type) {
    if (name.isEmpty) return;
    final had = vars[name];
    vars[name] = had == null || had == type ? type : 'Object?';
  }

  // Walks behaviors and every nested action list (OnTap actions, Health hurt/death, …).
  void walk(Object? node) {
    switch (node) {
      case List l:
        l.forEach(walk);
      case Map m:
        final props = m['props'] is Map ? m['props'] as Map : m;
        String s(String k) => props[k] is String ? props[k] as String : '';
        switch (m['type']) {
          case 'Emit' || 'OnEvent':
            if (s('event').isNotEmpty) events.add(s('event'));
            if (m['type'] == 'OnEvent') addVar(s('store'), 'Object?');
          case 'AddVariable':
            addVar(s('name'), 'double');
          case 'SetVariable':
            addVar(s('name'), 'String');
          case 'Health':
            addVar(s('variable'), 'double');
        }
        m.values.forEach(walk);
    }
  }

  for (final a in assets) {
    final json = scenes[a];
    if (json is! Map) continue;
    if (json['variables'] case Map v) {
      for (final MapEntry(:key, :value) in v.entries) {
        addVar('$key', switch (value) {
          num _ => 'double',
          String _ => 'String',
          bool _ => 'bool',
          _ => 'Object?',
        });
      }
    }
    walk(json['entities']);
  }

  final b = StringBuffer()
    ..writeln('// GENERATED by Kiln from assets/scenes — do not edit.')
    ..writeln('// The editor rewrites it on every scene save; or run `dart run kiln:types`.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'package:kiln/kiln.dart';")
    ..writeln()
    ..writeln('abstract final class KilnScenes {');
  final sceneIds = _Names(const {'all'});
  for (final a in assets) {
    b.writeln('  static const ${sceneIds.of(_stem(a))} = ${_lit(a)};');
  }
  b
    ..writeln('  static const all = [${assets.map(_lit).join(', ')}];')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class KilnEvents {');
  final eventIds = _Names();
  for (final e in events.toList()..sort()) {
    b.writeln('  static const ${eventIds.of(e)} = ${_lit(e)};');
  }
  b
    ..writeln('}')
    ..writeln()
    ..writeln('extension KilnVars on GameVariables {');
  final varIds = _Names(_varsReserved);
  for (final name in vars.keys.toList()..sort()) {
    final id = varIds.of(name), k = _lit(name);
    final (type, read) = switch (vars[name]) {
      'double' => ('double', 'number($k)'),
      'String' => ('String', 'string($k)'),
      'bool' => ('bool', 'flag($k)'),
      _ => ('Object?', 'this[$k]'),
    };
    b
      ..writeln('  $type get $id => $read;')
      ..writeln('  set $id($type v) => this[$k] = v;');
  }
  b.writeln('}');
  return b.toString();
}

String _stem(String asset) {
  final f = asset.split('/').last;
  return f.endsWith('.kiln.json') ? f.substring(0, f.length - 10) : f.split('.').first;
}

String _lit(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

// Names GameVariables already has: an extension member with one of these would be silently ignored.
const _varsReserved = {
  'number', 'string', 'flag', 'seed', 'reset', 'addListener', 'removeListener', 'notifyListeners', //
  'hasListeners', 'dispose', 'hashCode', 'runtimeType', 'toString', 'noSuchMethod',
};

// Reserved words only; built-in identifiers (get, on, type, …) are valid member names.
const _dartReserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', 'default', 'do', 'else', 'enum', //
  'extends', 'false', 'final', 'finally', 'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return',
  'super', 'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with', 'await', 'yield',
};

/// lowerCamelCase identifiers, unique within one namespace.
class _Names {
  _Names([this.extra = const {}]);

  final Set<String> extra;
  final _used = <String>{};

  String of(String raw) {
    final words = raw.split(RegExp(r'[^A-Za-z0-9]+')).where((w) => w.isNotEmpty).toList();
    var id = [
      for (final (i, w) in words.indexed)
        i == 0 ? w[0].toLowerCase() + w.substring(1) : w[0].toUpperCase() + w.substring(1),
    ].join();
    if (id.isEmpty || RegExp(r'^[0-9]').hasMatch(id)) id = 'v$id';
    if (_dartReserved.contains(id) || extra.contains(id)) id = '${id}Var';
    var unique = id;
    for (var n = 2; !_used.add(unique); n++) {
      unique = '$id$n';
    }
    return unique;
  }
}
